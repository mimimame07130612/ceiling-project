#!/usr/bin/env python3
# K116 アルミ角パイプ25×50×2（A6063-T5）のリンクの継手のつなぎ方（案）。部屋を含まない部分詳細（F7 d）。単位mm
# 入力：K115（A3案）、A06-003（Oのピン φ12両持ち・球面滑り軸受 外径22、A：ピンを長リンクに固定・OAに無給油ブッシュ2個 間隔15、
#       B・C′：コの字で両持ち・ピンを長リンクに固定・ブッシュはコの字の両側 間隔35）、K115の計算本体でA3を回した継手の値（安全率込み）：
#       面外モーメント B 142.8・C 120.2・A 64.9 N·m、ブッシュ1個の力 A 4511・B 4279・C 3594 N
import subprocess, html
TS = subprocess.run(['date','+%y%m%d%H%M'],capture_output=True,text=True,env={'TZ':'Asia/Tokyo'}).stdout.strip()
e = html.escape
W, H = 1350, 1050
AL, BL, ST, PN, BU, K = '#B4B2A9', '#85B7EB', '#5F5E5A', '#333', '#E6A23C', '#9b6fc0'
o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="Noto Sans CJK JP, sans-serif">', f'<rect width="{W}" height="{H}" fill="#fff"/>',
 '<text x="20" y="30" font-size="18" font-weight="bold">K116　アルミ角パイプ25×50×2のリンクの継手のつなぎ方（案）</text>',
 f'<text x="20" y="50" font-size="11" fill="#555">作成 {TS}　部屋を含まない部分詳細（F7 d）。単位mm。形・寸法はすべて仮。差し込み部品・スリーブ・ボルトの寸法は未選定</text>']
def T(x,y,s,fs=11,c='#222',a='middle'): o.append(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{fs}" fill="{c}" text-anchor="{a}">{e(s)}</text>')
def R(x,y,w,h,c,op=0.6,dash=False,sw=1): o.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="{c}" fill-opacity="{op}" stroke="#444" stroke-width="{sw}" {"stroke-dasharray=\"4 2\"" if dash else ""}/>')
def C(x,y,r,c,op=0.8): o.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="{c}" fill-opacity="{op}" stroke="#444"/>')
# ---- (1) 面内の側面（リンクの長さ方向）
T(20, 85, '(1) 長リンク（B–A–C、ピン間 896.8）と短リンクOA（O–A、448.4）：面内で見た差し込み部品の位置', 13, '#000', 'start')
S1 = 1.15; x0 = 60; y0 = 120
def link(xa, length, y, label, ends, mids):
    R(xa, y, length*S1, 50*S1*0.6, AL, 0.35)
    for (p, w_, lab) in ends+mids:
        R(xa+(p-w_/2)*S1, y+2, w_*S1, 50*S1*0.6-4, BL, 0.7)
    T(xa-6, y+20, label, 12, '#000', 'end')
# 長リンク：両端は B・C、中央は A。端の差し込み部品 長さ60、中央 長さ50（位置合わせしてボルト留め）
ins = []
link(x0+70, 896.8+60, y0, '長リンク', [(30,60,'C'),(896.8+30,60,'B')], [(448.4+30,50,'A')])
for p, lab in ((30,'C（C′）'),(448.4+30,'A'),(896.8+30,'B')):
    C(x0+70+p*S1, y0+17, 6*S1*0.8, PN); T(x0+70+p*S1, y0+55, lab, 11)
link(x0+70, 448.4+60, y0+90, '短リンクOA', [(30,60,'O'),(448.4+30,60,'A')], [])
for p, lab in ((30,'O'),(448.4+30,'A')):
    C(x0+70+p*S1, y0+107, 6*S1*0.8, PN); T(x0+70+p*S1, y0+145, lab, 11)
T(x0+70, y0+175, '灰：角パイプ（外25×50、肉厚2、内21×46）。青：中実の差し込み部品（内21×46に入る角材、業者加工）。ピン穴は差し込み部品ごと貫通。端はピン中心から30はみ出す', 11, '#333', 'start')
T(x0+70, y0+193, '長リンクの中央Aの差し込み部品は、パイプの端から差し込んで位置を合わせ、h方向のボルト2本（M5、仮）で留める', 11, '#333', 'start')
# ---- (2) 断面：ピン軸（x）を含み、リンクの面に直角に切った断面
S2 = 6.0
def sec_base(cx, cy, title):
    T(cx, cy-175, title, 12, '#000')
def tube_sec(cx, cy):   # x方向25、リンクの幅方向50（図の縦）
    R(cx-12.5*S2, cy-25*S2, 25*S2, 50*S2, AL, 0.5)
    R(cx-10.5*S2, cy-23*S2, 21*S2, 46*S2, BL, 0.75)
yS = 560
# B（C′も同じ）
cx = 230
sec_base(cx, yS, '(2) B・C′：ピンを長リンクに固定、ブッシュはコの字の両側')
tube_sec(cx, yS)
R(cx-12.5*S2, yS-10*S2, 25*S2, 20*S2, ST, 0.85)          # 鋼スリーブ 外径20（仮）
R(cx-30*S2, yS-6*S2, 60*S2, 12*S2, PN, 0.9)              # ピン φ12
for sx in (-17.5, 17.5):
    R(cx+(sx-5)*S2, yS-15*S2, 10*S2, 30*S2, K, 0.35)     # コの字の板（厚10）
    R(cx+(sx-5)*S2, yS-8*S2, 10*S2, 16*S2, BU, 0.9)      # ブッシュ
T(20, yS+40*S2, '鋼スリーブ（外径20、仮）を差し込み部品ごと圧入し、ピンφ12をスリーブに固定', 10, '#222', 'start')
T(20, yS+40*S2+16, 'ブッシュ中心間35（A06-003）。面外モーメントはスリーブ→差し込み部品→パイプで受ける', 10, '#222', 'start')
# A（長リンク側にピン固定、OAにブッシュ2個）
cx = 640
sec_base(cx, yS, '(3) A：ピンを長リンクに固定、OA側にブッシュ2個（間隔15）')
tube_sec(cx-12.5*S2, yS)       # 長リンク（x 0〜25）
tube_sec(cx+12.5*S2, yS)       # OA（x 25〜50）を重ねる
R(cx-25*S2, yS-10*S2, 25*S2, 20*S2, ST, 0.85)            # 長リンク側のスリーブ
R(cx-27*S2, yS-6*S2, 54*S2, 12*S2, PN, 0.9)              # ピン
for bx in (12.5-7.5, 12.5+7.5):
    R(cx+(bx-4)*S2, yS-8*S2, 8*S2, 16*S2, BU, 0.9)       # ブッシュ2個（長さ8、仮）
T(cx-12.5*S2, yS+30*S2, '長リンク', 10); T(cx+12.5*S2, yS+30*S2, 'OA', 10)
T(cx, yS+40*S2, 'OAのブッシュは差し込み部品とパイプの両側の壁を通して圧入（ブッシュ中心間15）', 10)
# O（OA側に球面滑り軸受、ピンは両持ち）
cx = 1080
sec_base(cx, yS, '(4) O：OAに球面滑り軸受（外径22）、ピンφ12両持ち')
tube_sec(cx, yS)
R(cx-8*S2, yS-11*S2, 16*S2, 22*S2, BU, 0.9)               # 球面滑り軸受 外径22・幅16（仮）
R(cx-28*S2, yS-6*S2, 56*S2, 12*S2, PN, 0.9)
R(cx-26*S2, yS-20*S2, 6*S2, 40*S2, K, 0.35); R(cx+20*S2, yS-20*S2, 6*S2, 40*S2, ST, 0.5)
T(cx-23*S2, yS-22*S2, '外板', 10); T(cx+23*S2, yS-22*S2, 'スペーサー', 10)
T(cx, yS+40*S2, '軸受は差し込み部品に圧入。パイプの壁は軸受の外径より大きく逃がす（仮）', 10)
# ---- 確認の数値
yC = 880
lines = ['確かめが要る点（K115の計算本体でA3を回した値、安全率込み）：',
 '・ピン固定部の面圧：長リンクがピンを固定して受ける面外モーメント B 142.8・C 120.2・A 64.9 N·m。差し込み部（x方向の長さ25）で受けると、',
 '　端の面圧の目安 6M/(D·L²)：ピンφ12を直接アルミに入れると B で 114 MPa（A6063-T5の仮の許容110を超える）→ 鋼スリーブ外径20にすると 69 MPa（余裕1.6）',
 '・ブッシュ1個の力 A 4,511・B 4,279・C′ 3,594 N（K114の平鋼・自重ありより小さい）。ブッシュの許容値は製品未選定のため未確認',
 '・差し込み部品とパイプの留め方（ボルト・接着・ピンの貫通だけ）、差し込み部品の材質、スリーブの圧入代は未検討',
 '・質量の目安：差し込み部品 21×46×60 は約0.16kg（アルミ）、片側5個（長リンク3・OA2）で約0.75kg。リンク本体と合わせ片側約1.8kg（ピン・ブッシュ・スリーブ別）']
for i, s in enumerate(lines): T(20, yC+i*22, s, 12, '#222', 'start')
o.append('</svg>')
open(f'/mnt/user-data/outputs/{TS}_K116_アルミ角パイプのリンクの継手.svg','w',encoding='utf-8').write('\n'.join(o))
print(TS, 6*142.8e3/(12*25**2), 6*142.8e3/(20*25**2), 21*46*60*2.7e-6)
